// JPEG XR signature regression (GHSA-2jrc-675j-96jw, GHSA-994h-2f6q-8wh6).
//
// ReadContainer() and ReadWMIHeader() read the file signature into small
// stack buffers (2 and 8 bytes) and passed them to strstr(), which needs a
// null terminator. File-controlled nonzero bytes removed the terminator and
// strstr() read past the buffer. Run under AddressSanitizer to see the stack
// read; the checks also verify that both inputs are rejected cleanly.
#include "FreeImage.h"

#include <cstdio>
#include <cstdlib>

// Container signature: begins 24 24 instead of "II".
static const BYTE kContainer[20] = {
    0x24, 0x24, 0x24, 0x24, 0x24, 0x24, 0x5f, 0x69, 0x7f, 0x00, 0x69, 0x69, 0x69, 0x69, 0x69, 0x69,
    0x6d, 0x00, 0x00, 0x38
};

// Codestream signature: eight nonzero bytes after a valid container header.
static const BYTE kCodestream[114] = {
    0x49, 0x49, 0xbc, 0x01, 0x1e, 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff, 0x50, 0x00, 0x0c, 0xff,
    0x8d, 0x9c, 0x8d, 0x79, 0x03, 0x7e, 0x8d, 0x01, 0x00, 0x53, 0x00, 0x7f, 0x80, 0x00, 0x04, 0x00,
    0xc0, 0xbc, 0x00, 0x31, 0x01, 0x00, 0x00, 0x00, 0x53, 0x00, 0x00, 0x00, 0xd8, 0xd8, 0x00, 0x00,
    0xef, 0xe8, 0x0e, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0xed, 0xff, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x0a, 0x21,
    0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xf9, 0xe4, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x15, 0x00,
    0x01, 0x13, 0x03, 0x8d, 0x8d, 0x50, 0x51, 0x20, 0x00, 0x00, 0x10, 0x7f, 0x80, 0x00, 0x00, 0x00,
    0x00, 0x0a
};

static void check(bool ok, const char *message) {
    if (!ok) {
        std::fprintf(stderr, "JXR signature test failed: %s\n", message);
        std::exit(1);
    }
}

static void loadAsJxr(const BYTE *data, size_t size) {
    // The data is copied because FreeImage_OpenMemory does not take ownership.
    BYTE *copy = static_cast<BYTE *>(std::malloc(size));
    check(copy != NULL, "allocation failed");
    for (size_t i = 0; i < size; ++i) copy[i] = data[i];
    FIMEMORY *memory = FreeImage_OpenMemory(copy, static_cast<DWORD>(size));
    check(memory != NULL, "could not open memory stream");
    FIBITMAP *bitmap = FreeImage_LoadFromMemory(FIF_JXR, memory, 0);
    check(bitmap == NULL, "malformed signature was accepted");
    FreeImage_CloseMemory(memory);
    std::free(copy);
}

int main() {
    FreeImage_Initialise(FALSE);
    loadAsJxr(kContainer, sizeof(kContainer));
    loadAsJxr(kCodestream, sizeof(kCodestream));
    FreeImage_DeInitialise();
    std::puts("JXR signature tests passed");
    return 0;
}
